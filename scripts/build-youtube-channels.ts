function merge(existing: Channel[], extra: Channel[]): Channel[] {
  const byId = new Map<string, Channel>();
  const handles = new Set<string>();
  for (const channel of [...existing, ...extra]) {
    const handle = channel.handle.toLowerCase();
    if (handles.has(handle) || byId.has(channel.id)) continue;
    handles.add(handle);
    byId.set(channel.id, channel);
  }
  return [...byId.values()];
}

function main() {
  const file = path.join(
    process.cwd(),
    'data',
    'sources',
    'youtube-channels.json',
  );
  const existing = JSON.parse(readFileSync(file, 'utf8')) as Channel[];
  const merged = merge(existing, expand(PACK));
  writeFileSync(file, `${JSON.stringify(merged, null, 2)}\n`);
  const languages = new Set(merged.map((item) => item.language));
  const en = merged.filter((item) => item.language === 'en').length;
  const es = merged.filter((item) => item.language === 'es').length;
  console.log(
    `Wrote ${merged.length} YouTube channels (${en} en · ${es} es · ${languages.size} languages).`,
  );
}

main();
