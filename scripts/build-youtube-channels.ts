function expand(rows: Row[]): Channel[] {
  return rows.map((row) => {
    const [handle, title, language, creators, description, tags, genres, cc] =
      row;
    const place = PLACE[cc] ?? ['north-america', 'Unknown', cc];
    const id = `yt-${handle
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')}`;
    return {
      id,
      handle,
      title,
      language,
      creators: creators.split('|').map((name) => name.trim()),
      description,
      tags: tags.split(',').map((tag) => tag.trim()),
      genres: genres.split(',').map((genre) => genre.trim()),
      region: place[0],
      country: place[1],
      countryCode: cc,
      youtube: `https://www.youtube.com/@${handle}`,
    };
  });
}

